-- 保留四维 scope、run 和 lifetime 外键，去掉对可删除 memories 的反向外键。
DO $$
DECLARE item RECORD;
BEGIN
 FOR item IN
   SELECT conrelid::regclass AS relation, conname
   FROM pg_constraint
   WHERE contype='f' AND confrelid='memories'::regclass
     AND conrelid IN ('memory_exposures'::regclass,'memory_assessments'::regclass,'memory_feedback_receipts'::regclass)
 LOOP
   EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', item.relation, item.conname);
 END LOOP;
END $$;

ALTER TABLE memories ADD COLUMN storage_row_id BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX memory_visible ON memories(organization_id,tenant_id,project_id,agent_uid,scope,lifetime,project,id);
CREATE INDEX memory_recent ON memories(organization_id,tenant_id,project_id,agent_uid,storage_row_id DESC);
CREATE INDEX memory_exposure_lifetime ON memory_exposures(organization_id,tenant_id,project_id,agent_uid,lifetime,created_at_ms DESC);
CREATE INDEX memory_ingest_pending ON memory_ingest_retries(organization_id,tenant_id,project_id,agent_uid,retry_at_ms) WHERE attempts<3;

